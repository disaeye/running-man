"use client";

import { useMemo } from "react";
import { Sparkles } from "lucide-react";
import { Section } from "@shared/ui/Section";
import { zoneFor } from "@shared/lib/metric-zone";

export interface PeriodReadingProps {
  readonly loading: boolean;
  readonly error: string | null;
  /** PMC points inside the active range, oldest first. */
  readonly points: readonly { readonly ctl: number | null; readonly tsb: number | null }[];
  readonly pillars: readonly { readonly title: string; readonly verdict: string }[];
  readonly rangeLabel: string;
}

/**
 * The period reading: a short, fixed-height block of prose at the foot of the
 * overview.
 *
 * The text is computed from the numbers in the active range, and says so. It is
 * not generated by a language model yet, so the provenance line names the data
 * instead of claiming an AI wrote it. When the generation service lands it
 * replaces `digest()` behind the same four states — loading, insufficient data,
 * failed, ready — and the panel keeps its shape.
 */
export function PeriodReading({ loading, error, points, pillars, rangeLabel }: PeriodReadingProps) {
  const digest = useMemo(() => buildDigest(points, pillars), [points, pillars]);
  const insufficient = !loading && error == null && points.length < 14;

  return (
    <Section
      title="本期解读"
      testId="analysis-period-reading"
      action={<span className="text-caption1 text-text-muted">{rangeLabel}</span>}
    >
      <div>
        <div className="p-5 text-subheadline leading-relaxed text-text-secondary">
        {loading ? (
          <p role="status" aria-busy="true">正在计算这一期的变化…</p>
        ) : error ? (
          <p className="text-error" role="alert">
            这一期没有算出来：{error}
          </p>
        ) : insufficient ? (
          <p>
            这个范围只有 {points.length} 天数据。解读需要至少 14 天，还差 {14 - points.length} 天。
          </p>
        ) : (
          <ol className="space-y-1.5">
            {digest.map((line) => (
              <li key={line} className="flex gap-2">
                <span className="mt-2 size-1 shrink-0 rounded-full bg-accent-strong" aria-hidden="true" />
                <span>{line}</span>
              </li>
            ))}
          </ol>
        )}
      </div>

      {!loading && !error && !insufficient && (
        <p className="mt-3 flex items-center gap-1.5 border-t border-border-subtle pt-2 text-caption1 text-text-muted">
          <Sparkles className="size-3.5" aria-hidden="true" />
          由本期训练数据计算，生成服务尚未接入
        </p>
      )}
      </div>
    </Section>
  );
}

function buildDigest(
  points: PeriodReadingProps["points"],
  pillars: PeriodReadingProps["pillars"],
): string[] {
  const lines: string[] = [];
  const first = points[0];
  const last = points[points.length - 1];

  if (first?.ctl != null && last?.ctl != null) {
    const delta = Math.round((last.ctl - first.ctl) * 10) / 10;
    const direction = delta >= 0 ? "升" : "降";
    lines.push(
      `体能从 ${Math.round(first.ctl)} ${direction}到 ${Math.round(last.ctl)}，共 ${Math.abs(delta)}，${Math.abs(delta) < 2 ? "基本持平" : delta > 0 ? "在积累" : "在回落"}。`,
    );
  }
  if (last?.tsb != null) {
    const zone = zoneFor("tsb", last.tsb);
    lines.push(
      `状态收在 ${Math.round(last.tsb)}，${zone ? `${zone.label}：${zone.description}` : "暂无区间"}`,
    );
  }
  for (const pillar of pillars) {
    lines.push(`${pillar.title}：${pillar.verdict}`);
  }
  return lines;
}
