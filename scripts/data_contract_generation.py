from __future__ import annotations

import json
import pprint
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Final

import yaml
from data_contract_schema import CONTRACT_FILES

REPO_ROOT: Final = Path(__file__).resolve().parents[1]
GENERATED_HEADER_PY: Final = '"""Generated by scripts/generate_data_contract.py. DO NOT EDIT."""\n'
GENERATED_HEADER_TS: Final = "// Generated by scripts/generate_data_contract.py. DO NOT EDIT.\n"
PYTHON_OUTPUTS: Final = {
    "__init__.py": "",
    "sources.py": "sources",
    "sports.py": "sports",
    "stream_metrics.py": "stream_metrics",
    "metrics.py": "metrics",
    "algorithms.py": "algorithms",
    "readiness_bands.py": "readiness_bands",
}
TYPESCRIPT_OUTPUTS: Final = {
    "source-registry.ts": "sources",
    "sport-registry.ts": "sports",
    "stream-metric-registry.ts": "stream_metrics",
    "metric-registry.ts": "metrics",
    "algorithm-registry.ts": "algorithms",
    "readiness-bands.ts": "readiness_bands",
}

@dataclass(frozen=True, slots=True)
class Contract:
    sources: list[dict[str, object]]
    sports: list[dict[str, object]]
    stream_metrics: list[dict[str, object]]
    metrics: list[dict[str, object]]
    algorithms: list[dict[str, object]]
    readiness_bands: list[dict[str, object]]


def load_contract(contract_directory: Path) -> Contract:
    collections: dict[str, list[dict[str, object]]] = {}
    for collection, file_name in CONTRACT_FILES.items():
        with (contract_directory / file_name).open(encoding="utf-8") as contract_file:
            parsed = yaml.safe_load(contract_file)
        entries = parsed[collection]
        sort_key = "min_score" if collection == "readiness_bands" else "key"
        collections[collection] = sorted(
            entries, key=lambda entry: entry[sort_key]  # type: ignore[index]
        )
    return Contract(**collections)


def generated_outputs(contract_directory: Path) -> dict[Path, str]:
    contract = load_contract(contract_directory)
    outputs: dict[Path, str] = {}
    api_directory = REPO_ROOT / "apps/api/src/domain/generated"
    web_directory = REPO_ROOT / "apps/web/shared/config/generated"
    for file_name, collection in PYTHON_OUTPUTS.items():
        outputs[api_directory / file_name] = render_python(file_name, collection, contract)
    for file_name, collection in TYPESCRIPT_OUTPUTS.items():
        outputs[web_directory / file_name] = render_typescript(collection, contract)
    return outputs


def render_python(file_name: str, collection: str, contract: Contract) -> str:
    match file_name:
        case "__init__.py":
            return GENERATED_HEADER_PY
        case "sources.py":
            return render_python_definitions("Source", "SOURCE_DEFINITIONS", contract.sources)
        case "sports.py":
            return render_python_definitions("Sport", "SPORT_DEFINITIONS", contract.sports)
        case "stream_metrics.py":
            return render_python_stream_metrics(contract.stream_metrics)
        case "metrics.py":
            return render_python_definitions("Metric", "METRIC_DEFINITIONS", contract.metrics)
        case "algorithms.py":
            return render_python_definitions(
                "Algorithm", "ALGORITHM_DEFINITIONS", contract.algorithms
            )
        case "readiness_bands.py":
            return render_python_readiness_bands(contract.readiness_bands)
        case unreachable:
            raise ValueError(f"unknown Python generated file {unreachable}")


def render_python_definitions(
    enum_name: str, definition_name: str, entries: list[dict[str, object]]
) -> str:
    enum_members = "\n".join(
        f"    {upper_snake(str(entry['key']))} = {json.dumps(entry['key'])}" for entry in entries
    )
    rendered = python_literal(entries)
    return (
        f"{GENERATED_HEADER_PY}\nfrom enum import StrEnum\nfrom typing import Final\n\n\n"
        f"class {enum_name}(StrEnum):\n{enum_members}\n\n"
        f"{definition_name}: Final = {rendered}\n"
    )


def render_python_stream_metrics(entries: list[dict[str, object]]) -> str:
    enum_members = "\n".join(
        f"    {upper_snake(str(entry['key']))} = {json.dumps(entry['key'])}" for entry in entries
    )
    aliases = {
        alias: entry["key"]
        for entry in entries
        for alias in [str(entry["key"]), *entry["adapter_only_aliases"]]
    }
    return (
        f"{GENERATED_HEADER_PY}\nfrom enum import StrEnum\nfrom typing import Final\n\n\n"
        f"class StreamMetric(StrEnum):\n{enum_members}\n\n"
        f"STREAM_METRIC_DEFINITIONS: Final = {python_literal(entries)}\n\n"
        f"STREAM_METRIC_ALIASES: Final = {python_literal(aliases)}\n"
    )


def render_python_readiness_bands(entries: list[dict[str, object]]) -> str:
    rendered = python_literal(entries)
    return (
        f"{GENERATED_HEADER_PY}\nfrom typing import Final\n\n"
        f"READINESS_BANDS: Final = {rendered}\n"
    )


def render_typescript(collection: str, contract: Contract) -> str:
    entries = getattr(contract, collection)
    if collection == "readiness_bands":
        return render_typescript_readiness_bands(entries)
    names = {
        "sources": ("Source", "SOURCE_REGISTRY"),
        "sports": ("Sport", "SPORT_REGISTRY"),
        "stream_metrics": ("StreamMetric", "STREAM_METRIC_REGISTRY"),
        "metrics": ("Metric", "METRIC_REGISTRY"),
        "algorithms": ("Algorithm", "ALGORITHM_REGISTRY"),
    }
    singular, registry_name = names[collection]
    entry_type = f"{singular}Definition"
    type_name = f"{singular}Key"
    aliases = alias_entries(entries)
    return (
        f"{GENERATED_HEADER_TS}\n"
        f"export const {registry_name} = {typescript_literal(index_by_key(entries))} as const;\n\n"
        f"export type {type_name} = keyof typeof {registry_name};\n"
        f"export type {entry_type} = (typeof {registry_name})[{type_name}];\n\n"
        f"export const {singular.upper()}_ALIASES: Record<string, {type_name}> = "
        f"{typescript_literal(aliases)};\n\n"
        f"export function get{singular}Definition(key: string): {entry_type} | undefined {{\n"
        f"  const canonicalKey = {singular.upper()}_ALIASES[key];\n"
        f"  return canonicalKey === undefined ? undefined : {registry_name}[canonicalKey];\n"
        f"}}\n"
    )


def render_typescript_readiness_bands(entries: list[dict[str, object]]) -> str:
    by_level = {str(entry["level"]): entry for entry in entries}
    return (
        f"{GENERATED_HEADER_TS}\n"
        f"export const READINESS_BANDS = {typescript_literal(entries)} as const;\n\n"
        f"export const READINESS_BANDS_BY_LEVEL = "
        f"{typescript_literal(by_level)} as const;\n\n"
        f"export type ReadinessLevel = "
        f"{' | '.join(json.dumps(str(e['level'])) for e in entries)};\n\n"
        f"export interface ReadinessBand {{\n"
        f"  readonly min_score: number;\n"
        f"  readonly level: ReadinessLevel;\n"
        f"  readonly label: string;\n"
        f"  readonly max_intensity: string;\n"
        f"  readonly color: string;\n"
        f"  readonly recommendation: string;\n"
        f"}}\n\n"
        f"export function readinessBandForScore(score: number): ReadinessBand {{\n"
        f"  for (let i = READINESS_BANDS.length - 1; i >= 0; i--) {{\n"
        f"    const band = READINESS_BANDS[i];\n"
        f"    if (band && score >= band.min_score) return band;\n"
        f"  }}\n"
        f"  return READINESS_BANDS[0]!;\n"
        f"}}\n"
    )


def index_by_key(entries: list[dict[str, object]]) -> dict[str, dict[str, object]]:
    return {str(entry["key"]): entry for entry in entries}


def alias_entries(entries: list[dict[str, object]]) -> dict[str, str]:
    aliases: dict[str, str] = {}
    for entry in entries:
        key = str(entry["key"])
        aliases[key] = key
        for alias in entry.get("aliases", []):
            aliases[str(alias)] = key
        for alias in entry.get("adapter_only_aliases", []):
            aliases[str(alias)] = key
    return aliases


def python_literal(value: object) -> str:
    return pprint.pformat(value, width=88, sort_dicts=True)


def typescript_literal(value: object) -> str:
    encoded = json.dumps(value, ensure_ascii=False, separators=(", ", ": "), sort_keys=True)
    return re.sub(r'"([A-Za-z_$][A-Za-z0-9_$]*)":', r"\1:", encoded)


def upper_snake(value: str) -> str:
    return value.upper()
