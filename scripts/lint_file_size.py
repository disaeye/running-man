#!/usr/bin/env python3
"""Scan source files and report those exceeding a maximum line count.

Skips __init__.py files, blank lines, and comment-only lines.
"""

import argparse
import sys
from collections.abc import Iterable
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCAN_ROOTS = ("apps", "docs", "scripts")
DEFAULT_ROOT_FILES = ("CLAUDE.md", "CONTRIBUTING.md", "README.md")
DEFAULT_SUFFIXES = frozenset({".js", ".jsx", ".md", ".mjs", ".py", ".ts", ".tsx"})
EXCLUDED_DIRS = frozenset(
    {
        ".cache",
        ".git",
        ".mypy_cache",
        ".next",
        ".omo",
        ".pytest_cache",
        ".ruff_cache",
        ".venv",
        "build",
        "coverage",
        "dist",
        "htmlcov",
        "node_modules",
        "playwright-report",
        "test-results",
        "venv",
    }
)

# Files exempt from the LOC limit, with the reason each one is exempt.
# Keep this list as small as possible: hand-written source must stay within
# the limit; only generated artifacts, long-form docs, and standalone dev
# utilities live here.
ALLOWLIST: dict[str, str] = {
    # Generated by scripts/generate_data_contract.py — regenerated, not hand-edited.
    "apps/api/src/domain/generated/metrics.py": "generated codegen output (DO NOT EDIT header)",
    "apps/web/shared/config/generated/metric-registry.ts": (
        "generated codegen output (DO NOT EDIT header)"
    ),
    # Generated by the OpenAPI client codegen — regenerated on contract change.
    "apps/web/shared/api/generated/clients.ts": "generated OpenAPI client",
    # Long-form design reference; length is content-driven, not code.
    "apps/web/DESIGN.md": "long-form design document",
    # Standalone demo-data seed generator (CLI script, not module source).
    "apps/api/scripts/seed_data.py": "standalone demo-data seed CLI",
    # Frozen historical migration; must not be edited after the fact.
    "apps/api/alembic/versions/f6a7b8c9d0e1_project_wellness_metrics_into_eav.py": "frozen historical migration",
    # SQL-heavy migration carrying two full fact-function bodies; same class as f6a7b8c9d0e1.
    "apps/api/alembic/versions/g0a1b2c3d4e5_expand_wellness_and_weather_data.py": "SQL-heavy frozen migration",
    # Standalone contract-validation CLI, not module source.
    "scripts/validate_data_contract.py": "standalone contract-validation CLI",
}


class ParsedArgs(argparse.Namespace):
    paths: list[Path]
    max_loc: int

    def __init__(self) -> None:
        super().__init__()
        self.paths = []
        self.max_loc = 250


def count_loc(path: Path) -> int:
    code_lines = 0
    with path.open(encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if is_ignored_line(stripped, path):
                continue
            code_lines += 1
    return code_lines


def is_ignored_line(stripped: str, path: Path) -> bool:
    if not stripped:
        return True
    match path.suffix:
        case ".py" | ".md":
            return stripped.startswith("#")
        case ".js" | ".jsx" | ".mjs" | ".ts" | ".tsx":
            return stripped.startswith(("//", "/*", "*"))
        case _:
            return False


def has_excluded_part(path: Path) -> bool:
    return any(part in EXCLUDED_DIRS for part in path.parts)


def collect_explicit_files(paths: Iterable[Path]) -> list[Path]:
    files: list[Path] = []
    for path in paths:
        path = path.resolve()
        if path.is_file():
            files.append(path)
        elif path.is_dir():
            files.extend(
                p
                for p in path.rglob("*")
                if p.is_file()
                and p.suffix in DEFAULT_SUFFIXES
                and not has_excluded_part(p.relative_to(REPO_ROOT))
            )
    return files


def collect_default_files() -> list[Path]:
    files: list[Path] = []
    for root_name in DEFAULT_SCAN_ROOTS:
        root = REPO_ROOT / root_name
        if root.is_dir():
            files.extend(
                path
                for path in root.rglob("*")
                if path.is_file()
                and path.suffix in DEFAULT_SUFFIXES
                and not has_excluded_part(path.relative_to(REPO_ROOT))
            )
    files.extend(
        path
        for name in DEFAULT_ROOT_FILES
        if (path := REPO_ROOT / name).is_file()
    )
    return files


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Reject files exceeding max LOC. With no paths, scan repo source/docs/scripts."
    )
    _ = parser.add_argument("paths", nargs="*", type=Path, help="Files or directories to scan")
    _ = parser.add_argument("--max-loc", type=int, default=250, help="Maximum allowed LOC per file")
    args = ParsedArgs()
    _ = parser.parse_args(namespace=args)

    files = collect_explicit_files(args.paths) if args.paths else collect_default_files()

    exit_code = 0
    for f in sorted(files):
        if f.name == "__init__.py":
            continue
        rel = f.relative_to(REPO_ROOT).as_posix()
        if rel in ALLOWLIST:
            continue
        loc = count_loc(f)
        if loc > args.max_loc:
            print(f"FAIL {f}  ({loc} LOC exceeds {args.max_loc})")
            exit_code = 1

    if exit_code == 0:
        print("All files within size limit.")

    return exit_code


if __name__ == "__main__":
    sys.exit(main())
